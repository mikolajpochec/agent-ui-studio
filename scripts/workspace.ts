// The working copy a studio edits, so the user's project stays untouched until the studio is finished.
// The copy is cheap: files are cloned (copy-on-write where the filesystem supports it), dependency folders are
// linked, and build caches are left out for the copy's dev server to regenerate. On finish, `apply` writes back
// what changed in the copy, refusing any file the user changed in the original meanwhile.
import {
  copyFileSync, chmodSync, constants, existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, readlinkSync,
  rmSync, statSync, symlinkSync, writeFileSync,
} from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";

// Regenerated by dev servers and builds: never copied, never applied back.
const SKIP = new Set([".git", ".next", ".nuxt", ".output", ".svelte-kit", ".turbo", ".vite", ".cache", ".parcel-cache", ".expo", ".angular", "DerivedData", ".gradle", ".ui-studio"]);
// Big, shared and not edited: linked to the original's.
const LINK = new Set([".venv", "venv", "Pods"]);
// node_modules gets its own folder of links, so caches a dev server writes into it (node_modules/.vite) stay in the copy.
const OWN_CACHES = new Set([".vite", ".vite-temp", ".cache", ".tmp"]);
const GENERATED = /(\.timestamp-\d+.*\.mjs|\.tsbuildinfo)$/;

const hash = (f: string) => createHash("sha1").update(readFileSync(f)).digest("hex");

export function createWorkspace(original: string, work: string) {
  const manifest: Record<string, string> = {};
  const walk = (rel: string) => {
    const src = join(original, rel), dst = join(work, rel);
    mkdirSync(dst, { recursive: true });
    for (const e of readdirSync(src, { withFileTypes: true })) {
      const r = rel ? join(rel, e.name) : e.name;
      const s = join(original, r), d = join(work, r);
      if (e.isSymbolicLink()) { symlinkSync(readlinkSync(s), d); continue; }
      if (e.isDirectory()) {
        if (SKIP.has(e.name)) continue;
        if (LINK.has(e.name)) { symlinkSync(s, d); continue; }
        if (e.name === "node_modules") {
          mkdirSync(d);
          for (const m of readdirSync(s)) if (!OWN_CACHES.has(m)) symlinkSync(join(s, m), join(d, m));
          continue;
        }
        walk(r);
      } else if (e.isFile()) {
        copyFileSync(s, d, constants.COPYFILE_FICLONE);
        chmodSync(d, statSync(s).mode);
        manifest[r] = hash(s);
      }
    }
  };
  walk("");
  return manifest;
}

// Files of a tree as the copy sees them (no linked or skipped folders).
function files(root: string) {
  const out: string[] = [];
  const walk = (rel: string) => {
    for (const e of readdirSync(join(root, rel), { withFileTypes: true })) {
      const r = rel ? join(rel, e.name) : e.name;
      if (e.isDirectory() && !SKIP.has(e.name) && !LINK.has(e.name) && e.name !== "node_modules") walk(r);
      else if (e.isFile()) out.push(r);
    }
  };
  walk("");
  return out;
}

const fileHash = (f: string) => { try { return lstatSync(f).isFile() ? hash(f) : null; } catch { return null; } };

// Ignored by the original's git (generated files, local caches): never written back.
function gitIgnored(original: string, rels: string[]) {
  if (!rels.length || !existsSync(join(original, ".git"))) return new Set<string>();
  const r = Bun.spawnSync(["git", "-C", original, "check-ignore", "--stdin"], { stdin: Buffer.from(rels.join("\n")) });
  return new Set(r.stdout.toString().split("\n").filter(Boolean));
}

export type Changes = { changed: string[]; created: string[]; deleted: string[]; conflicts: string[]; skipped: string[] };

// What the copy changed, and whether each change can go into the original safely.
export function diffWorkspace(original: string, work: string, manifest: Record<string, string>, exclude: string[] = []): Changes {
  const ex = new Set(exclude);
  const c: Changes = { changed: [], created: [], deleted: [], conflicts: [], skipped: [] };
  const seen = new Set<string>();
  const cand: { rel: string; kind: "changed" | "created" | "deleted" }[] = [];
  for (const rel of files(work)) {
    seen.add(rel);
    if (ex.has(rel)) continue;
    const h = fileHash(join(work, rel));
    if (manifest[rel] === h) continue;
    cand.push({ rel, kind: rel in manifest ? "changed" : "created" });
  }
  for (const rel of Object.keys(manifest)) if (!seen.has(rel) && !ex.has(rel)) cand.push({ rel, kind: "deleted" });
  const ignored = gitIgnored(original, cand.map((x) => x.rel));
  for (const { rel, kind } of cand) {
    if (ignored.has(rel) || GENERATED.test(rel)) { c.skipped.push(rel); continue; }
    const now = fileHash(join(original, rel));
    const base = manifest[rel] ?? null;
    const want = kind === "deleted" ? null : fileHash(join(work, rel));
    if (now === want) continue; // the original already has it
    if (now !== base) { c.conflicts.push(rel); continue; } // the user changed it meanwhile
    c[kind].push(rel);
  }
  return c;
}

export function applyWorkspace(original: string, work: string, changes: Changes) {
  for (const rel of [...changes.changed, ...changes.created]) {
    const s = join(work, rel), d = join(original, rel);
    mkdirSync(dirname(d), { recursive: true });
    copyFileSync(s, d);
    chmodSync(d, statSync(s).mode);
  }
  for (const rel of changes.deleted) rmSync(join(original, rel), { force: true });
}

export function saveManifest(file: string, m: Record<string, string>) { writeFileSync(file, JSON.stringify(m)); }
export function loadManifest(file: string): Record<string, string> { return JSON.parse(readFileSync(file, "utf8")); }
